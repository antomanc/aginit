import fs from 'node:fs';
import path from 'node:path';
import { AginitConfig } from '../config/schema.js';
import { presetPlatform } from '../config/defaults.js';
import { detectProject, projectCommands } from '../detect/index.js';
import {
  activeCapabilities,
  CapabilityDescriptor,
  CATALOG,
  e2eDirFor,
  GuideContext,
  MicroDoc,
  Platform,
  Stack
} from '../registry/index.js';
import { readTextFile, safeWriteFile } from '../utils/fs.js';
import { logger } from '../utils/logger.js';

export interface ProjectProfile extends GuideContext {
  active: CapabilityDescriptor[];
}

/** Platform and stack: saved in v2 configs, detected for older ones. */
export function resolvePlatformStack(
  config: AginitConfig,
  targetDir?: string
): { platform: Platform; stack: Stack } {
  const detected = targetDir && (!config.platform || !config.stack) ? detectProject(targetDir) : null;
  return {
    platform:
      config.platform ??
      (config.preset !== 'generic' ? presetPlatform(config.preset) : (detected?.platform ?? 'cli')),
    stack: config.stack ?? (detected && detected.stack !== 'unknown' ? detected.stack : 'node')
  };
}

export function projectProfile(
  config: AginitConfig,
  options: { targetDir?: string; scripts?: Record<string, string> } = {}
): ProjectProfile {
  const { platform, stack } = resolvePlatformStack(config, options.targetDir);
  const active = activeCapabilities(config);
  const ids = new Set(active.map((c) => c.id));
  return {
    platform,
    stack,
    active,
    has: (id) => ids.has(id),
    commands: projectCommands(options.targetDir ?? '.', stack, {
      packageManager: config.packageManager,
      scripts: options.scripts
    }),
    e2eDir: e2eDirFor(stack)
  };
}

export const DOCS_DIR = path.join('docs', 'agents');
export const GENERATED_MARKER =
  '<!-- aginit:managed — generated by npx @antomanc/aginit. Delete this line to take ownership of this file. -->';
export const LEGACY_GENERATED_MARKER =
  '<!-- Generated by aginit from aginit.config.json. Rerun `aginit` to refresh; delete this line to edit by hand. -->';

const DOC_TITLES: Record<MicroDoc, string> = {
  testing: 'Testing',
  'ui-verification': 'Live UI verification',
  workflows: 'Engineering workflows & skills'
};

const skillNames = (capability: CapabilityDescriptor) =>
  capability.install.flatMap((step) => (step.kind === 'skills-sh' ? step.skills : []));

function testingIntro(profile: ProjectProfile): string[] {
  const { commands } = profile;
  const rows: Array<[string, string | undefined]> = [
    ['Build', commands.build],
    ['Typecheck', commands.typecheck],
    ['Lint / analyze', commands.lint],
    ['Test', commands.test],
    ['Unit test', commands.unitTest],
    ['E2E', commands.e2e]
  ];
  const lines = rows.filter(([, cmd]) => cmd).map(([label, cmd]) => `- ${label}: \`${cmd}\``);
  return lines.length
    ? ['Run the full check before calling a change done:', ...lines]
    : ['Record the project build and test commands here once they exist.'];
}

function workflowsExtras(profile: ProjectProfile): string[] {
  // Skill capabilities without their own guide still show up, so new registry
  // entries and custom skill repos are documented without extra code.
  const plain = profile.active.filter(
    (c) => !c.guide && c.install.some((step) => step.kind === 'skills-sh')
  );
  const bullet = (c: CapabilityDescriptor) => {
    const skills = skillNames(c);
    const label = skills.length ? skills.map((s) => '`' + s + '`').join(', ') : `\`${c.id}\``;
    return `- ${label}: ${c.description}.`;
  };
  const discipline = plain.filter((c) => c.category === 'discipline');
  const others = plain.filter((c) => c.category !== 'discipline');
  return [
    ...(discipline.length ? ['## Discipline (apply to every change)', ...discipline.map(bullet)] : []),
    ...(others.length ? ['', '## Other skills', ...others.map(bullet)] : [])
  ];
}

// Drivers come before the design review that uses them; unit runners before E2E.
const SECTION_ORDER = ['methodology', 'ui-driver', 'design', 'testing-engine', 'context-guard'];
const sectionRank = (c: CapabilityDescriptor) => {
  const category = SECTION_ORDER.indexOf(c.category);
  const index = CATALOG.indexOf(c);
  return (category === -1 ? SECTION_ORDER.length : category) * 1000 + (index === -1 ? 999 : index);
};

/** Markdown for one micro-doc, or null when no active capability contributes to it. */
export function renderMicroDoc(doc: MicroDoc, profile: ProjectProfile): string | null {
  const sections = profile.active
    .filter((c) => c.guide?.doc === doc)
    .sort((a, b) => sectionRank(a) - sectionRank(b))
    .map((c) => c.guide!.render(profile));
  const extras = doc === 'workflows' ? workflowsExtras(profile) : [];
  if (sections.length === 0 && extras.length === 0) return null;
  const intro =
    doc === 'testing'
      ? testingIntro(profile)
      : doc === 'workflows'
        ? [
            'Skills live in `.agents/skills/` (linked into `.claude/skills/` for Claude Code). Invoke one by name',
            '(for example `/tdd`), or let the agent pick it from its description.'
          ]
        : ['Verify UI changes in the running app, not only in tests.'];
  const body = [`# ${DOC_TITLES[doc]}`, '', ...intro, '', ...sections.flatMap((s) => [s, ''])];
  if (extras.length) body.push(...extras, '');
  return [GENERATED_MARKER, ...body].join('\n').replace(/\n{3,}/g, '\n\n').trimEnd() + '\n';
}

export const MICRO_DOCS: MicroDoc[] = ['testing', 'ui-verification', 'workflows'];

export function microDocPath(doc: MicroDoc): string {
  return path.join(DOCS_DIR, `${doc}.md`).split(path.sep).join('/');
}

/** Checks if a micro-doc's content still carries an aginit managed marker. */
export function isManagedMicroDoc(text: string | null): boolean {
  if (text === null) return true;
  const firstLine = text.split(/\r?\n/, 1)[0].trim();
  return (
    firstLine.startsWith(GENERATED_MARKER) ||
    firstLine.startsWith(LEGACY_GENERATED_MARKER) ||
    /^<!--\s*aginit:managed(?:\b[^>]*)?-->/.test(firstLine) ||
    /^<!--\s*Generated by aginit\b/.test(firstLine)
  );
}

/** Docs aginit owns: files it wrote that still carry the generated marker. */
function ownedByAginit(file: string): boolean {
  return isManagedMicroDoc(readTextFile(file));
}

/**
 * Write the docs/agents/ micro-docs for the active capabilities. A doc whose
 * marker line was removed belongs to the user and is never touched; a doc no
 * capability contributes to any more is deleted. Returns the docs that exist.
 */
export function setupMicroDocs(
  targetDir: string,
  profile: ProjectProfile,
  options: { dryRun?: boolean; silent?: boolean } = {}
): MicroDoc[] {
  const { dryRun = false, silent = false } = options;
  const present: MicroDoc[] = [];
  for (const doc of MICRO_DOCS) {
    const file = path.join(targetDir, DOCS_DIR, `${doc}.md`);
    const content = renderMicroDoc(doc, profile);
    if (!ownedByAginit(file)) {
      if (!silent) logger.dim(`${microDocPath(doc)} was edited by hand, preserving it.`);
      present.push(doc);
      continue;
    }
    if (content === null) {
      if (fs.existsSync(file)) {
        if (dryRun) logger.dim(`[dry-run] Would remove file: ${file}`);
        else fs.rmSync(file);
      }
      continue;
    }
    present.push(doc);
    if (readTextFile(file) !== content)
      safeWriteFile(file, content, { overwrite: true, dryRun, silent });
  }
  return present;
}

/** Docs that will exist for a profile (used when rendering AGENTS.md without a target). */
export function plannedMicroDocs(profile: ProjectProfile): MicroDoc[] {
  return MICRO_DOCS.filter((doc) => renderMicroDoc(doc, profile) !== null);
}
